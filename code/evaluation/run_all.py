"""The full evaluation workflow: run every check and write the measured results into evaluation_report.md.

    python code/evaluation/run_all.py

1. predicts the 32 public samples and scores them against sample_output.csv
   (status, step P/R/F1, field and sequence accuracy, per-case failures);
2. runs the custom evaluation cases (custom_cases.py);
3. checks the submitted output.csv (all 518 rows) for contract violations and future citations;
4. runs the component checks: evidence parsers vs gold citations, screenshot transcription vs a
   hand reading, intent vs hand labels, and identity/link recall.

The results replace the block between the RESULTS markers in evaluation_report.md.
"""

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODE = HERE.parent
REPO_ROOT = CODE.parent
sys.path.insert(0, str(CODE))
sys.path.insert(0, str(HERE))

import custom_cases  # noqa: E402
from check_output import check  # noqa: E402

# code/main.py and code/evaluation/main.py share a module name; load the evaluator by path.
_spec = importlib.util.spec_from_file_location("evaluation_main", HERE / "main.py")
_evaluator = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_evaluator)
evaluate, load = _evaluator.evaluate, _evaluator.load

PY = sys.executable
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def summary_line(script: str, label: str) -> str:
    """The script's summary line starting with `label`."""
    out = subprocess.run([PY, str(CODE / script)], capture_output=True, text=True, cwd=REPO_ROOT,
                         encoding="utf-8", errors="replace")
    lines = [line.strip() for line in out.stdout.splitlines() if line.strip().startswith(label)]
    return lines[-1] if lines else f"(no summary; exit {out.returncode})"


def sample_metrics() -> tuple[dict, str]:
    subprocess.run([PY, str(CODE / "main.py"), "--requests", "sample_deletion_requests.csv", "--out", "sample_predictions.csv"],
                   check=True, capture_output=True, cwd=REPO_ROOT)
    m = evaluate(load(REPO_ROOT / "dataset/sample_output.csv"), load(REPO_ROOT / "sample_predictions.csv"))
    failures = []
    for case_id, g_status, p_status, g_keys, p_keys in m["failures"]:
        missing = [k for k in g_keys if k not in p_keys]
        extra = [k for k in p_keys if k not in g_keys]
        detail = "; ".join([f"missing {k[3]} {k[2]}" for k in missing] + [f"extra {k[3]} {k[2]}" for k in extra])
        failures.append(f"| {case_id} | {g_status} | {p_status} | {detail} |")
    return m, "\n".join(failures)


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="output.csv", help="predictions file to validate (repo-relative)")
    parser.add_argument("--report", default=str(HERE / "evaluation_report.md"),
                        help="report whose RESULTS block is regenerated")
    args = parser.parse_args()

    m, failures = sample_metrics()
    custom = custom_cases.run()
    regression = subprocess.run([PY, str(HERE / "regression_tests.py")], capture_output=True, text=True, cwd=REPO_ROOT,
                                encoding="utf-8", errors="replace").stdout
    regression_rows = [line for line in regression.splitlines() if line.startswith(("PASS", "FAIL"))]
    regression_summary = next((line for line in regression.splitlines() if "regression tests pass" in line), "(not run)")
    stats, problems = check(REPO_ROOT / args.output, "deletion_requests.csv")
    components = {
        "Evidence parsers vs every gold evidence citation (`scripts/check_parsers.py`)": summary_line("scripts/check_parsers.py", "pass"),
        "Screenshot transcription vs hand reading (`scripts/check_vision.py`)": summary_line("scripts/check_vision.py", "resources:"),
        "Intent classifier vs hand labels (`scripts/check_intent.py`)": summary_line("scripts/check_intent.py", "texts:"),
        "Identity + resource linking recall on gold resources (`scripts/check_linking.py`)": summary_line("scripts/check_linking.py", "link recall:"),
    }
    fa = m["field_accuracy"]
    confusion = "\n".join(f"| {g} | {p} | {c} |" for (g, p), c in sorted(m["confusion"].items()))
    block = f"""{START}
_Generated by `python code/evaluation/run_all.py`; do not edit by hand._

### Public samples (32 cases, `dataset/sample_output.csv`)

| Metric | Value |
|---|---:|
| Case-level deletion-status accuracy | {m['status_accuracy']:.1%} |
| Step precision | {m['step_precision']:.1%} |
| Step recall | {m['step_recall']:.1%} |
| Step F1 | {m['step_f1']:.1%} |
| Sequence accuracy (steps_json identical, order included) | {m['sequence_accuracy']:.1%} |
| Missing / extra steps | {m['missing_steps']} / {m['extra_steps']} |
| Cases with the right steps in the wrong order | {m['misordered_cases']} |

Field-level accuracy (position-aligned steps): phase {fa['phase']:.1%}, system_id {fa['system_id']:.1%},
resource_id {fa['resource_id']:.1%}, operation {fa['operation']:.1%}, state {fa['state']:.1%},
evidence_id {fa['evidence_id']:.1%}.

| Gold status | Predicted | Cases |
|---|---|---:|
{confusion}

Cases that are not an exact match ({len(m['failures'])}):

| Case | Gold | Predicted | Difference |
|---|---|---|---|
{failures}

### Custom evaluation cases ({sum(ok for _, ok, _ in custom)}/{len(custom)} pass)

| Case | What it tests | Result |
|---|---|---|
""" + "\n".join(f"| `{c.name}` | {c.purpose} | {'PASS' if ok else 'FAIL: ' + '; '.join(p)} |" for c, ok, p in custom) + f"""

### Regression and adversarial suite (`evaluation/regression_tests.py`)

{regression_summary}. Scenario numbers follow the required list (1 historical identifiers ...
15 malformed or contradictory evidence); `[synthetic]` marks tests with fabricated inputs.

```
""" + "\n".join(regression_rows) + f"""
```

### Submitted output.csv (all {stats['rows']} rows, no gold available)

Contract and grounding checks (`evaluation/check_output.py`): {len(problems)} problems across
{stats['rows']} rows and {stats['citations']} evidence citations (header, one row per request, sort
order, step schema and numbering, phase/operation/state agreement, evidence rules per status, every
cited id exists, no citation captured after the case's audit_at).

### Component checks

| Check | Result |
|---|---|
""" + "\n".join(f"| {k} | {v} |" for k, v in components.items()) + f"""
{END}"""

    report = Path(args.report)
    text = report.read_text(encoding="utf-8")
    text = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    report.write_text(text, encoding="utf-8")
    print(f"status {m['status_accuracy']:.1%}  F1 {m['step_f1']:.1%}  sequence {m['sequence_accuracy']:.1%}  "
          f"custom {sum(ok for _, ok, _ in custom)}/{len(custom)}  output problems {len(problems)}")
    print(f"  {regression_summary}")
    for k, v in components.items():
        print(f"  {v}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
