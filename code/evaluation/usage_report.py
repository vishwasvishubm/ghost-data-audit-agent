"""Write code/evaluation/usage_report.md from the ledger of the full run that produced output.csv.

    python code/main.py                          # writes evaluation/usage_ledger_deletion_requests.json
    python code/evaluation/usage_report.py
"""

import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent

# USD per 1M tokens (input, output). Google list prices as published by third-party aggregators in
# October 2026; gemini-3.8-flash is on introductory pricing until 2026-12-31.
PRICES = {
    "gemini-3.8-flash": (0.75, 3.75),
    "gemini-3.5-flash-lite": (0.30, 2.50),
}


def cost(model: str, tokens_in: int, tokens_out: int) -> float:
    price_in, price_out = PRICES[model]
    return tokens_in / 1e6 * price_in + tokens_out / 1e6 * price_out


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--ledger", default=str(HERE / "usage_ledger_deletion_requests.json"))
    parser.add_argument("--out", default=str(HERE / "usage_report.md"))
    args = parser.parse_args()
    ledger = json.loads(Path(args.ledger).read_text(encoding="utf-8"))
    n = ledger["requests"]
    rows: dict[tuple, dict] = defaultdict(lambda: {"calls": 0, "live": 0, "in": 0, "out": 0})
    for c in ledger["calls"]:
        r = rows[(c["provider"], c["model"], c["purpose"])]
        r["calls"] += 1
        r["live"] += not c["cached"]
        r["in"] += c["input_tokens"]
        r["out"] += c["output_tokens"]

    total = {"calls": 0, "live": 0, "in": 0, "out": 0, "cost": 0.0}
    table = []
    for (provider, model, purpose), r in sorted(rows.items()):
        c = cost(model, r["in"], r["out"])
        for k in ("calls", "live", "in", "out"):
            total[k] += r[k]
        total["cost"] += c
        table.append(
            f"| {provider} | `{model}` | {purpose} | {r['calls']} | {r['in']:,} | {r['out']:,} | "
            f"{r['in'] + r['out']:,} | ${c:.4f} | ${c / n:.6f} |"
        )
    tokens = total["in"] + total["out"]

    md = f"""# Usage Report

Final full-dataset run: `python code/main.py` over `dataset/{ledger['requests_file']}` ({n} requests),
producing `output.csv`. Generated by `code/evaluation/usage_report.py` from the run's call ledger.

## How the models are used

The audit itself (identity resolution, evidence linking, state reconstruction, policy, step
planning) is deterministic code and makes **no model calls**. Gemini is used for exactly two
narrow tasks, each called once per distinct input and cached on disk (`code/.cache/`):

| Task | Model | Input | Calls |
|---|---|---|---|
| Screenshot transcription | `gemini-3.8-flash` (vision, low thinking) | each of the 11 evidence screenshots | 1 per screenshot |
| Request intent classification | `gemini-3.5-flash-lite` (low thinking) | the 398 distinct request texts across sample + evaluation requests, 100 per call | 4 |

## Per-model and overall totals (one full run)

Token counts are those reported by the API when each call was made; a rerun reads the same
answers from the cache.

| Provider | Model | Purpose | Model calls | Input tokens | Output tokens | Total tokens | Est. cost (USD) | Est. cost / request |
|---|---|---|---:|---:|---:|---:|---:|---:|
{chr(10).join(table)}
| **Overall** | | | **{total['calls']}** | **{total['in']:,}** | **{total['out']:,}** | **{tokens:,}** | **${total['cost']:.4f}** | **${total['cost'] / n:.6f}** |

- Requests: {n}
- Average tokens per request: {tokens / n:,.1f} ({total['in'] / n:,.1f} input, {total['out'] / n:,.1f} output)
- Average model calls per request: {total['calls'] / n:.3f}
- Calls made live in the final run: {total['live']} (all others served from the committed cache)
- Output tokens include thinking tokens, which are billed as output.

## Cost basis

| Model | Input $/1M | Output $/1M |
|---|---:|---:|
""" + "\n".join(f"| `{m}` | {p[0]:.2f} | {p[1]:.2f} |" for m, p in PRICES.items()) + """

Prices are Google's published list prices as reported by pricing aggregators in October 2026
(`gemini-3.8-flash` is on introductory pricing until 2026-12-31; it doubles from 2027-01-01).
The calls were actually made on the Gemini API free tier, so the amount billed was $0; the
figures above are what the same run would cost at list price.

## Token efficiency decisions

- **Deterministic core.** Only the two tasks that need perception or language understanding use a
  model; ~2,900 evidence observations, 4,011 activity rows and all policy decisions cost nothing.
- **Deduplication.** 550 requests share 398 distinct texts; each text is classified once.
- **Batching.** 100 texts per intent call: 4 calls instead of 398.
- **Low thinking.** For transcription, lowering thinking cut output tokens about 5x per screenshot
  (2,427 -> 523 measured on the same image) with an identical transcription.
- **Cache keyed by model, settings, prompt, schema and input hash**, so reruns are free,
  deterministic and work without an API key.
"""
    Path(args.out).write_text(md, encoding="utf-8")
    print(f"wrote usage_report.md: {total['calls']} calls, {tokens:,} tokens, est. ${total['cost']:.4f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
